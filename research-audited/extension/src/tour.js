const fs = require('fs');
const path = require('path');

/**
 * CodeTour-compatible tour files (microsoft/codetour, MIT).
 * Verified against codetour/schema.json: a tour is
 *   { title, description?, ref?, isPrimary?, steps: [{ file?, line?, title?, description, selection? }] }
 * with `title` and `steps` required, and each step's `description` required.
 * Files live under `.vscode/codeTour/<name>.tour`.
 */

const TOUR_DIR = path.join('.vscode', 'codeTour');

/** Build a tour object from walkthrough beats. */
function toTour(beats, { title, file, firstLine = 1, startColumn = 0, endColumn = 0 }) {
  return {
    title: title || 'Voice walkthrough',
    description: 'Narrated code walkthrough generated by Code Walkthrough (voice).',
    isPrimary: false,
    steps: beats.map((b) => {
      // CodeTour stores lines and selection coordinates 1-based.
      const line = Math.max(1, firstLine + Math.max(0, (b.line ?? 1) - 1));
      return {
        file,
        line,
        selection: {
          start: { line, character: startColumn + 1 },
          end: { line, character: endColumn + 1 },
        },
        // codetour renders this as markdown; keep the spoken line verbatim
        // under a separate key so the tour stays human-readable.
        description: b.say,
        say: b.say,
      };
    }),
  };
}

function sanitize(name) {
  return String(name).replace(/[^a-zA-Z0-9._-]+/g, '-').replace(/^-+|-+$/g, '') || 'tour';
}

/** Write a tour into the workspace; returns the absolute path. */
function saveTour(workspaceRoot, tour) {
  const dir = path.join(workspaceRoot, TOUR_DIR);
  fs.mkdirSync(dir, { recursive: true });
  let base = sanitize(tour.title);
  let target = path.join(dir, `${base}.tour`);
  let n = 2;
  while (fs.existsSync(target)) target = path.join(dir, `${base}-${n++}.tour`);
  fs.writeFileSync(target, JSON.stringify(tour, null, 2) + '\n', 'utf8');
  return target;
}

/** Load and validate a tour file. Throws with a readable message. */
function loadTour(tourPath) {
  const raw = JSON.parse(fs.readFileSync(tourPath, 'utf8'));
  if (typeof raw.title !== 'string' || !Array.isArray(raw.steps)) {
    throw new Error('not a valid code tour: needs "title" and "steps"');
  }
  const steps = raw.steps
    .filter((s) => s && typeof s.description === 'string')
    .map((s) => ({
      file: s.file,
      line: typeof s.line === 'number' ? s.line : 1, // CodeTour is 1-based
      say: typeof s.say === 'string' ? s.say : stripMarkdown(s.description),
      description: s.description,
    }));
  return { title: raw.title, description: raw.description, steps };
}

/** Tour steps are markdown; speech should not read markup aloud. */
function stripMarkdown(md) {
  return md
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[*_>#]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** List tour files in the workspace. */
function listTours(workspaceRoot) {
  const dir = path.join(workspaceRoot, TOUR_DIR);
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => f.endsWith('.tour')).map((f) => path.join(dir, f));
}

module.exports = { toTour, saveTour, loadTour, listTours, stripMarkdown, TOUR_DIR };
